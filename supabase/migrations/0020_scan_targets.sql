-- Products to scan: a working list of the most-bought packaged foods at Costco, Sam's Club,
-- Walmart, Aldi, Lidl and other big grocers, grouped so rival products can be compared
-- (compare_group: the name brand vs every store brand of the same thing).
--   todo     on the list
--   next     wanted soon: shown to members ("Wanted next") and preferred for "Scan this next"
--   scanned  done (scan_id links the scan when known)
--   skipped  not doing it
-- The admin edits the list on /products. Server-only like every other table (0003).

create table if not exists scan_targets (
  id uuid primary key default gen_random_uuid(),
  product text not null,
  store text not null default 'Any',
  category text not null,
  compare_group text,
  priority int not null default 50 check (priority between 0 and 100),
  status text not null default 'todo' check (status in ('todo', 'next', 'scanned', 'skipped')),
  scan_id uuid references scans on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product, store)
);
create index if not exists scan_targets_status_idx on scan_targets (status, priority desc);
alter table scan_targets enable row level security;

